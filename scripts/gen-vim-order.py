#!/usr/bin/env python3
# Regenerates tests/Backdafuckup.Testing/Vim/VimSchemaOrder.g.cs: the element order of vim25 request types for the fake
# vCenter, from the public WSDL/XSD that every vCenter serves under https://<vcenter>/sdk/ (vim.wsdl, vim-types.xsd,
# vim-messagetypes.xsd, core-types.xsd, query-types.xsd, query-messagetypes.xsd, reflect-*.xsd). Download them into one
# directory first; they are not kept in the repository.
# Usage: scripts/gen-vim-order.py <xsd dir> <method> [<method> ...] > tests/Backdafuckup.Testing/Vim/VimSchemaOrder.g.cs
import pathlib, re, sys
import xml.etree.ElementTree as ET

XS = "{http://www.w3.org/2001/XMLSchema}"
here = pathlib.Path(sys.argv[1])
types = {}     # name -> (base or None, [(element, type)])
methods = {}   # method element -> request type
for f in ["vim-types.xsd", "core-types.xsd", "query-types.xsd", "vim-messagetypes.xsd", "query-messagetypes.xsd", "reflect-types.xsd", "reflect-messagetypes.xsd"]:
    root = ET.parse(here / f).getroot()
    for ct in root.iter(XS + "complexType"):
        name = ct.get("name")
        if not name:
            continue
        base = None
        seq = None
        ext = ct.find(f"{XS}complexContent/{XS}extension")
        if ext is not None:
            base = ext.get("base").split(":")[-1]
            seq = ext.find(f"{XS}sequence")
        else:
            seq = ct.find(f"{XS}sequence")
        elems = []
        if seq is not None:
            for e in seq.findall(f"{XS}element"):
                elems.append((e.get("name"), (e.get("type") or "anyType").split(":")[-1]))
        types[name] = (base, elems)
    for el in root.findall(f"{XS}element"):
        if el.get("type"):
            methods[el.get("name")] = el.get("type").split(":")[-1]

for schema in ET.parse(here / "vim.wsdl").getroot().iter(XS + "schema"):
    for el in schema.findall(f"{XS}element"):
        if el.get("type"):
            methods[el.get("name")] = el.get("type").split(":")[-1]

wanted_methods = sys.argv[2:]
derived = {}
for name, (base, _) in types.items():
    if base:
        derived.setdefault(base, []).append(name)

def full(name):
    base, elems = types[name]
    return (full(base) if base and base in types else []) + elems

closure, todo = set(), []
for m in wanted_methods:
    t = methods[m]
    todo.append(t)
while todo:
    t = todo.pop()
    if t in closure or t not in types:
        continue
    closure.add(t)
    for _, et in full(t):
        if et.startswith("ArrayOf"):
            et = et[len("ArrayOf"):]
            et = et[0].upper() + et[1:] if et else et
        todo.append(et)
    if t not in ("DynamicData", "MethodFault", "RuntimeFault", "VimFault", "Event", "VmEvent"):
        todo.extend(derived.get(t, []))

out = ["// <auto-generated>", "// Element order of the vim25 request types, from the public XSD that vCenter serves under /sdk (vim-types.xsd,",
       "// vim-messagetypes.xsd, query-*.xsd, vim.wsdl). Only element names and their types: the fake vCenter checks that requests list",
       "// them in this order, as vCenter does. Regenerate with scripts/gen-vim-order.py when new methods are used.", "// </auto-generated>",
       "#nullable enable", "namespace Backdafuckup.Testing.Vim;", "", "internal static class VimSchemaOrder", "{",
       "    public static readonly IReadOnlyDictionary<string, string> Methods = new Dictionary<string, string>(StringComparer.Ordinal)", "    {"]
for m in sorted(wanted_methods):
    out.append(f'        ["{m}"] = "{methods[m]}",')
out += ["    };", "", "    public static readonly IReadOnlyDictionary<string, (string? Base, (string Name, string Type)[] Elements)> Types =",
        "        new Dictionary<string, (string? Base, (string Name, string Type)[] Elements)>(StringComparer.Ordinal)", "        {"]
for t in sorted(closure):
    base, elems = types[t]
    items = ", ".join(f'("{n}", "{ty}")' for n, ty in elems)
    out.append(f'            ["{t}"] = ({("\"" + base + "\"") if base else "null"}, [{items}]),')
out += ["        };", "}", ""]
print("\n".join(out))
print(f"// {len(closure)} types", file=sys.stderr)
